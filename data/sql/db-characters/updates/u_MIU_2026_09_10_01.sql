-- 5. 老记录迁移 (通用段 rank R -> 73-81 段 rank 72+R, 强度 5R%->3R%, 用户已确认接受 nerf)
--    幂等守卫: 只迁 rank<=9 的旧记录, 重复执行为空操作; 57011 无记录无需迁移
--    tier 记录不动(tier 编号=突破次数, 新旧体系语义一致)
-- ----------------------------------------------------------
UPDATE `character_item_upgrade` ciu
JOIN `item_instance` ii ON ii.guid = ciu.item_guid
JOIN `mod_item_upgrade_stats` sold ON sold.id = ciu.stat_id AND sold.stat_rank <= 9
JOIN `mod_item_upgrade_stats` snew ON snew.stat_type = sold.stat_type AND snew.stat_rank = sold.stat_rank + 72
SET ciu.stat_id = snew.id
WHERE ii.itemEntry IN (57008, 57009, 57010);
